let idioma = 'es';
const oyentes = new Set();

export function idiomaPorNavegador(lang) {
  const l = String(lang ?? (typeof navigator !== 'undefined' ? navigator.language : 'es') ?? 'es').toLowerCase();
  return l.startsWith('es') ? 'es' : 'en';
}

export function getIdioma() { return idioma; }

export function t(clave, vars) {
  const tabla = TEXTOS[idioma] || TEXTOS.es;
  let s = tabla[clave] ?? TEXTOS.es[clave] ?? clave;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return s;
}

export function onIdioma(fn) { oyentes.add(fn); return () => oyentes.delete(fn); }

function aplicarDom() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = idioma;
  document.querySelectorAll('[data-i18n]').forEach((n) => {
    n.textContent = t(n.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((n) => {
    n.setAttribute('placeholder', t(n.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((n) => {
    n.setAttribute('aria-label', t(n.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((n) => {
    n.setAttribute('title', t(n.getAttribute('data-i18n-title')));
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t('app.descripcion'));
  document.title = t('app.titulo');
  document.querySelectorAll('[data-idioma]').forEach((b) => {
    b.setAttribute('aria-pressed', b.getAttribute('data-idioma') === idioma ? 'true' : 'false');
  });
}

export function setIdioma(nuevo) {
  const sig = nuevo === 'en' ? 'en' : 'es';
  if (sig === idioma) { aplicarDom(); return idioma; }
  idioma = sig;
  if (typeof localStorage !== 'undefined') localStorage.setItem(CLAVE, idioma);
  aplicarDom();
  oyentes.forEach((fn) => { try { fn(idioma); } catch (_) {} });
  return idioma;
}

export function iniciarIdioma(almacen, langNavegador) {
  const ls = almacen ?? (typeof localStorage !== 'undefined' ? localStorage : null);
  const guardado = ls && (ls.getItem(CLAVE) === 'en' || ls.getItem(CLAVE) === 'es') ? ls.getItem(CLAVE) : null;
  idioma = guardado || idiomaPorNavegador(langNavegador);
  if (ls) ls.setItem(CLAVE, idioma);
  aplicarDom();
  return idioma;
}

